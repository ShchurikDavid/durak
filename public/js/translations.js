export function localize(text, language) {
  if (typeof text !== 'string' || language === 'ru') return text;
  const normalized = text.trim().replace(/\s+/g, ' ');
  const translated = translations[normalized]?.[language];
  if (translated) return text.replace(text.trim(), translated);
  const symbols = normalized.match(/^([^А-Яа-яA-Za-z0-9]*)([А-Яа-я].*)$/u);
  if (symbols && translations[symbols[2]]?.[language])
    return symbols[1] + translations[symbols[2]][language];
  const counter = normalized.match(/^(?:🟡 )?Игроков (\d+\/\d+)$/);
  if (counter) return (language === 'uk' ? 'Гравців ' : 'Players ') + counter[1];
  if (normalized.includes(' · '))
    return normalized
      .split(' · ')
      .map((part) => localize(part, language))
      .join(' · ');
  if (text.includes('\n'))
    return text
      .split('\n')
      .map((line) => localize(line, language))
      .join('\n');
  return text;
}
